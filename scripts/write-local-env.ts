// Writes apps/web/.env.local from the running local Supabase stack (`pnpm db:start` first).
// Local keys only; hosted keys are set in Vercel, never in files.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const raw = execSync("pnpm exec supabase status -o json", {
  encoding: "utf8",
  stdio: ["ignore", "pipe", "ignore"],
});
const status = JSON.parse(raw.slice(raw.indexOf("{"))) as Record<string, string | undefined>;

const required = (key: string) => {
  const value = status[key];
  if (!value) throw new Error(`supabase status did not return ${key}. Is the local stack running?`);
  return value;
};

const lines = [
  "# Generated by `pnpm env:local` from the local Supabase stack. Local keys only.",
  `NEXT_PUBLIC_SUPABASE_URL=${required("API_URL")}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${required("ANON_KEY")}`,
  `SUPABASE_SERVICE_ROLE_KEY=${required("SERVICE_ROLE_KEY")}`,
  "NEXT_PUBLIC_SITE_URL=http://localhost:3000",
  "NEXT_PUBLIC_AUTH_PROVIDERS=",
  "# Capture pipeline (ADR 0013). mock = fixture transcript and recipe, no API keys needed.",
  "# Set to live, with ANTHROPIC_API_KEY and a speech-to-text key, to use the real providers.",
  "AI_MODE=mock",
  "# Send pipeline events to the local Inngest dev server (pnpm dev:inngest).",
  "INNGEST_DEV=1",
  "",
];

writeFileSync(new URL("../apps/web/.env.local", import.meta.url), lines.join("\n"));
process.stdout.write("Wrote apps/web/.env.local\n");

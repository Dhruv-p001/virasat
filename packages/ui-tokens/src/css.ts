import { colors, fontSize, radius, sizing } from "./tokens.ts";

const rem = (value: number) => (value === 9999 ? "9999px" : `${value / 16}rem`);
const kebab = (name: string) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const colorVars = (palette: Record<string, string>, indent: string) =>
  Object.entries(palette)
    .map(([name, value]) => `${indent}--color-${kebab(name)}: ${value};`)
    .join("\n");

/**
 * Renders the Tailwind v4 theme. `theme.css` is generated from this and checked for drift in tests.
 * Dark mode follows the system unless an ancestor sets data-theme="light" or "dark".
 */
export function renderThemeCss(): string {
  const text = Object.entries(fontSize)
    .map(([name, value]) => `  --text-${name}: ${rem(value)};`)
    .join("\n");
  const size = Object.entries(sizing)
    .map(([name, value]) => `  --spacing-${kebab(name)}: ${rem(value)};`)
    .join("\n");
  const rounded = Object.entries(radius)
    .map(([name, value]) => `  --radius-${name}: ${rem(value)};`)
    .join("\n");

  return `/* Generated by packages/ui-tokens. Edit src/tokens.ts, then run \`pnpm --filter @virasat/ui-tokens generate:css\`. */
@theme {
${colorVars(colors.light, "  ")}
${text}
${size}
${rounded}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars(colors.dark, "    ")}
    color-scheme: dark;
  }
}

[data-theme="light"] {
${colorVars(colors.light, "  ")}
  color-scheme: light;
}

[data-theme="dark"] {
${colorVars(colors.dark, "  ")}
  color-scheme: dark;
}
`;
}

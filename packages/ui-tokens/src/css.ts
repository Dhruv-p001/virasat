import { colors, fontSize, radius, sizing } from "./tokens.ts";

const px = (value: number) => (value === 9999 ? "9999px" : `${value / 16}rem`);

/** Renders the Tailwind v4 theme. `theme.css` is generated from this and checked for drift in tests. */
export function renderThemeCss(): string {
  const light = Object.entries(colors.light)
    .map(([name, value]) => `  --color-${name}: ${value};`)
    .join("\n");
  const dark = Object.entries(colors.dark)
    .map(([name, value]) => `    --color-${name}: ${value};`)
    .join("\n");
  const text = Object.entries(fontSize)
    .map(([name, value]) => `  --text-${name}: ${px(value)};`)
    .join("\n");
  const size = Object.entries(sizing)
    .map(([name, value]) => `  --spacing-${kebab(name)}: ${px(value)};`)
    .join("\n");
  const rounded = Object.entries(radius)
    .map(([name, value]) => `  --radius-${name}: ${px(value)};`)
    .join("\n");

  return `/* Generated by packages/ui-tokens. Edit src/tokens.ts, then run \`pnpm --filter @virasat/ui-tokens generate:css\`. */
@theme {
${light}
${text}
${size}
${rounded}
}

@media (prefers-color-scheme: dark) {
  :root {
${dark}
  }
}
`;
}

function kebab(name: string): string {
  return name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}
